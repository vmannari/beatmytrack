"""Create a task-only source patch and prove exact forward/reverse application."""
import difflib
import hashlib
import json
from pathlib import Path
import shutil
import subprocess

ROOT = Path(__file__).resolve().parents[3]
HERE = Path(__file__).parent
existing = ["game/ui/car_showroom.gd", "game/ui/garage_page.gd", "AGENTS.md", "DEVELOPMENT_STATUS.md", "docs/PHASE_0_PLAN.md"]
new = ["game/ui/garage_super_wash.gd", "game/tests/test_super_wash_animation.gd", "docs/SUPER_WASH_ANIMATION_2026_11_02.md"]
new += [str(path.relative_to(ROOT)).replace("\\", "/") for path in [HERE / "run.py", HERE / "encode_motion.py", HERE / "checkpoint.py"]]
scratch = ROOT / "tmp/super-wash-animation-checkpoint"
scratch.mkdir(parents=True, exist_ok=True)
patch = []
hashes = {}
for relative in existing + new:
    current = ROOT / relative
    original = HERE / "before" / relative
    before = original.read_text(encoding="utf-8") if relative in existing else ""
    after = current.read_text(encoding="utf-8")
    patch.append(f"diff --git a/{relative} b/{relative}\n")
    if relative in new:
        patch.append("new file mode 100644\n")
    patch.extend(difflib.unified_diff(before.splitlines(keepends=True), after.splitlines(keepends=True), fromfile=f"a/{relative}" if relative in existing else "/dev/null", tofile=f"b/{relative}"))
    copy = scratch / relative
    copy.parent.mkdir(parents=True, exist_ok=True)
    if relative in existing:
        # Match the LF-normalized patch's working-tree line endings.
        copy.write_bytes(before.encode("utf-8"))
    else:
        copy.unlink(missing_ok=True)
    hashes[relative] = hashlib.sha256(current.read_bytes()).hexdigest()
target = HERE / "task.patch"
target.write_text("".join(patch), encoding="utf-8", newline="\n")
for flags in [["--check"], [], ["--check", "--reverse"], ["--reverse"]]:
    subprocess.run(["git", "apply", *flags, "--directory=tmp/super-wash-animation-checkpoint", str(target)], cwd=ROOT, check=True)
    if not flags:
        for relative in existing + new:
            assert (scratch / relative).read_text(encoding="utf-8") == (ROOT / relative).read_text(encoding="utf-8")
for relative in existing:
    assert (scratch / relative).read_text(encoding="utf-8") == (HERE / "before" / relative).read_text(encoding="utf-8")
for relative in new:
    assert not (scratch / relative).exists()
report = {
    "requirements": ["SWA01", "SWA02"],
    "source_sha256": hashes,
    "patch_sha256": hashlib.sha256(target.read_bytes()).hexdigest(),
    "forward_reverse_content_check": "pass; independent scratch files, main index untouched",
    "results": {"native_compatibility": "89 checks, 0 failures", "native_desktop_mobile": "89 checks, 0 failures", "retained_super_wash_compatibility": "257 checks, 0 failures", "retained_hose_headless": "81 checks, 0 failures", "initial_headless": "74 checks, 0 failures; certificate-store error retained", "motion_capture": "55 frames, 0 failures; production presentation manually stepped at 15 Hz"},
    "motion_sha256": hashlib.sha256((HERE / "super-wash-animation.png").read_bytes()).hexdigest(),
    "limitations": ["No physical-device test or performance claim", "Owner appearance acceptance and reload remain", "No owner-save/process, backend/live, deployment or main-index mutation", "Initial restricted dev entry startup failed; logs retained", "Build metadata regenerated by dev entry excluded; concurrent work retained"],
}
(HERE / "report.json").write_text(json.dumps(report, indent=2)+"\n", encoding="utf-8")
print(f"Task-only checkpoint: {len(existing)+len(new)} source files; forward/reverse/content checks pass")
