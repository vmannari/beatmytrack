from pathlib import Path
import json
import os
import re
import shutil
import subprocess

root = Path.cwd()
out = root / 'docs/evidence/track-editor-fixes-2026-10-28/preferred-check'
out.mkdir(exist_ok=True)
paths = ['game/project.godot','game/core/build_identity.gd']
original = {p:(root/p).read_bytes() for p in paths}
for p, data in original.items(): (out/Path(p).name).write_bytes(data)
profile = root / 'build/track-editor-fixes-2026-10-28/preferred-profile'
(profile/'Circuit01Lab').mkdir(parents=True,exist_ok=True)
(profile/'Circuit01Lab/backend.cfg').write_text('[backend]\nurl=""\n',encoding='utf-8')
env = {k:v for k,v in os.environ.items() if not k.startswith('BMT_')}
env.update(APPDATA=str(profile),LOCALAPPDATA=str(profile))
command = ['powershell','-NoProfile','-ExecutionPolicy','Bypass','-File','scripts/dev.ps1','-Action','CheckScript','-ScriptPath','res://tests/test_editor_admission_bytes.gd','-CommandTimeoutSeconds','60']
with (out/'wrapper.log').open('wb') as log:
    child = subprocess.Popen(command,env=env,stdout=log,stderr=subprocess.STDOUT)
    code = child.wait(timeout=100)
generated = root / f'build/logs/CheckScript-{child.pid}/client-build-identity.json'
statuses = {}
if generated.exists():
    shutil.copyfile(generated,out/generated.name)
    receipt = json.loads(generated.read_text(encoding='utf-8-sig'))
    identifier = receipt['build_id']
    expected = 'extends RefCounted\n# Generated by scripts/dev.ps1. Never recompute during gameplay.\nconst ID: String = "'+identifier+'"\nconst SOURCE_SHA256: String = "'+receipt['source_sha256']+'"\nconst GARAGE_PREVIEW_SHA256: String = "'+receipt['garage_preview_sha256']+'"\n'
    for p in paths:
        current = (root/p).read_bytes()
        (out/('after-'+Path(p).name)).write_bytes(current)
        own = expected if p.endswith('build_identity.gd') else re.sub(r'(?m)^config/version="[^\"]*"\r?$', 'config/version="'+identifier+'"', original[p].decode('utf-8'))
        if current.decode('utf-8') == own:
            (root/p).write_bytes(original[p]); statuses[p] = 'restored-own-generated-bytes'
        else: statuses[p] = 'preserved-concurrent-update'
(out/'receipt.json').write_text(json.dumps(dict(command=command,exit=code,metadata=statuses),indent=2),encoding='utf-8')
print(json.dumps(dict(exit=code,metadata=statuses)))
