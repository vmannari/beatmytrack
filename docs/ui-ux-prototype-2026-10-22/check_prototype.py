"""Browser checks for the isolated HTML concept. Never opens the game or backend."""
from pathlib import Path
import json
from playwright.sync_api import sync_playwright, expect

HERE = Path(__file__).resolve().parent
OUT = HERE / 'evidence'
OUT.mkdir(exist_ok=True)
CHECKS = []
ERRORS = []
EXTERNAL = []


def check(label, fn):
    fn()
    CHECKS.append(label)


def main():
    with sync_playwright() as p:
        browser = p.chromium.launch(headless=True, executable_path='C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe')
        page = browser.new_page(viewport={'width':1440,'height':1080})
        page.on('pageerror', lambda error: ERRORS.append(str(error)))
        page.on('request', lambda req: EXTERNAL.append(req.url) if req.url.startswith(('http:', 'https:')) else None)
        page.goto((HERE / 'index.html').as_uri(), wait_until='load')
        page.locator('[data-action="reset-demo"]').click()
        expect(page.locator('.welcome h1')).to_contain_text('PERSONAL BEST')
        CHECKS.append('Standalone file loads with embedded fonts and images')
        page.screenshot(path=str(OUT / '01-welcome-desktop.png'), full_page=True)
        page.locator('[data-action="first-race"]').click()
        expect(page.get_by_role('dialog')).to_contain_text('Your first five laps.')
        page.locator('[data-action="onboard-steering"][data-value="Analog joystick"]').click()
        page.get_by_role('dialog').get_by_role('button', name='Start racing', exact=True).click()
        assert page.evaluate("JSON.parse(localStorage.getItem('bmt-ui-concept-settings')).steering") == 'Analog joystick'
        expect(page.locator('#race-time')).to_be_visible()
        page.wait_for_timeout(300)
        expect(page.locator('#race-time')).not_to_have_text('00:00.000')
        page.locator('#finish-preview').click()
        expect(page.locator('.result-time')).to_have_text('01:23.407')
        expect(page.locator('.results-bottom .primary')).to_contain_text('Race again')
        page.locator('[data-action="result-tab"][data-value="Sectors"]').click()
        expect(page.locator('.standings-table')).to_contain_text('SECTOR')
        page.locator('[data-action="result-tab"][data-value="Speed"]').click()
        expect(page.locator('.chart')).to_be_visible()
        page.locator('[data-action="result-tab"][data-value="Track"]').click()
        page.locator('[data-action="lap"][data-value="0"]').click()
        expect(page.locator('.section-label')).to_contain_text('LAP 1')
        page.screenshot(path=str(OUT / '02-results-desktop.png'), full_page=True)
        page.locator('[data-action="results-next"]').click()
        expect(page.locator('.results-insight')).to_be_visible()
        CHECKS.append('First-race controls, moving illustration, finish, lap views and performance are connected')

        page.locator('#jump').select_option('settings')
        page.locator('[data-action="settings-section"][data-value="camera"]').click()
        page.locator('#pref-zoom').fill('11')
        expect(page.locator('#save-status')).to_contain_text('Unsaved changes')
        page.locator('.nav-tab[data-value="garage"]').click()
        expect(page.get_by_role('dialog')).to_contain_text('Keep your changes?')
        page.screenshot(path=str(OUT / '03-unsaved-changes-desktop.png'), full_page=True)
        page.locator('[data-action="stay"]').click()
        expect(page.locator('#pref-zoom')).to_have_value('11')
        page.locator('.nav-tab[data-value="garage"]').click()
        page.locator('[data-action="discard"]').click()
        expect(page.locator('.showroom')).to_be_visible()
        page.locator('#jump').select_option('settings')
        expect(page.locator('#pref-zoom')).to_have_value('30')
        page.locator('#pref-zoom').fill('17')
        page.locator('.nav-tab[data-value="garage"]').click()
        page.locator('[data-action="apply-leave"]').click()
        page.locator('#jump').select_option('settings')
        expect(page.locator('#pref-zoom')).to_have_value('17')
        expect(page.locator('[data-action="apply-settings"]')).to_be_disabled()
        page.reload()
        page.locator('#jump').select_option('settings')
        page.locator('[data-action="settings-section"][data-value="camera"]').click()
        expect(page.locator('#pref-zoom')).to_have_value('17')
        CHECKS.append('Stay preserves draft, Discard restores saved values, Apply & leave persists across reload')

        page.locator('[data-action="settings-section"][data-value="accessibility"]').click()
        page.get_by_role('checkbox', name='Reduced motion').check()
        page.get_by_role('checkbox', name='Larger text').check()
        page.locator('[data-action="apply-settings"]').click()
        expect(page.locator('#game')).to_have_class('game reduce-motion')
        expect(page.locator('body')).to_have_class('large-text')
        CHECKS.append('Reduced motion and larger supporting text apply in the prototype')

        page.locator('#jump').select_option('race')
        page.locator('#track-search').fill('zzz')
        expect(page.locator('.empty-state')).to_contain_text('No matching circuits')
        page.locator('[data-action="clear-search"]').click()
        expect(page.locator('.track-card')).to_have_count(5)
        page.locator('[data-action="bookmark"][data-value="1"]').click()
        expect(page.locator('[data-action="bookmark"][data-value="1"]')).to_have_attribute('aria-pressed','true')
        page.locator('[data-action="filters"]').click()
        page.locator('#filter-biome').select_option('winter')
        page.locator('[data-action="filter-apply"]').click()
        expect(page.locator('.track-card')).to_have_count(1)
        page.locator('[data-action="filters"]').click()
        page.locator('[data-action="filter-reset"]').click()
        page.locator('#scenario').select_option('offline')
        expect(page.locator('.offline-banner')).to_contain_text('Downloaded tracks')
        expect(page.locator('.track-card')).to_have_count(2)
        page.locator('[data-action="reconnect"]').click()
        expect(page.locator('.track-card')).to_have_count(5)
        page.locator('#scenario').select_option('error')
        expect(page.locator('.empty-state')).to_contain_text('Tracks could not load')
        page.locator('[data-action="reconnect"]').click()
        page.screenshot(path=str(OUT / '04-free-race-desktop.png'), full_page=True)
        CHECKS.append('Search, bookmarks, biome filtering, no matches, offline downloads and retry recoveries work')

        page.locator('#jump').select_option('garage')
        page.locator('[data-action="preview-car"][data-value="1"]').click()
        expect(page.locator('.showroom-label')).to_contain_text('Preview')
        page.locator('[data-action="confirm-car"]').click()
        expect(page.locator('.showroom-label')).to_contain_text('Selected for racing')
        page.locator('[data-action="colour"][data-value="2"]').click()
        expect(page.locator('[data-action="colour"][data-value="2"]')).to_have_attribute('aria-pressed','true')
        page.locator('[data-action="garage-section"][data-value="parts"]').click()
        page.locator('[data-action="part"][data-value="Twin louvres"]').click()
        expect(page.locator('.garage-side')).to_contain_text('Selected: Twin louvres')
        page.locator('[data-action="garage-section"][data-value="care"]').click()
        page.locator('[data-action="wash"]').last.click()
        expect(page.locator('.wash-meter')).to_have_attribute('aria-valuenow','44')
        page.locator('[data-action="garage-section"][data-value="customise"]').click()
        page.locator('[data-action="reset-appearance"]').click()
        page.locator('[data-action="appearance-confirm"]').click()
        expect(page.locator('[data-action="colour"][data-value="0"]')).to_have_attribute('aria-pressed','true')
        page.screenshot(path=str(OUT / '05-garage-desktop.png'), full_page=True)
        CHECKS.append('Car preview and confirmation, colour, parts, care and appearance reset change the intended state')

        page.locator('#jump').select_option('trophies')
        page.locator('[data-action="album"]').first.click()
        expect(page.locator('.album-actions')).to_contain_text('ACHIEVEMENTS')
        page.locator('[data-action="medal"][data-value="2"]').click()
        page.locator('[data-action="medal-display"]').click()
        page.locator('[data-action="album-close"]').click()
        expect(page.locator('.collection-heading').first).to_contain_text('3 / 5 on display')
        page.screenshot(path=str(OUT / '06-trophy-room-desktop.png'), full_page=True)
        CHECKS.append('Achievement album, detail sheet, display choice and return to Trophy Room work')

        page.locator('#jump').select_option('rivalry')
        expect(page.locator('.week-track')).to_have_count(5)
        page.locator('[data-action="rivalry-track"]').first.click()
        expect(page.locator('.track-detail-grid')).to_be_visible()
        page.locator('[data-action="start-rivalry"]').click()
        if page.get_by_role('dialog').is_visible():
            page.locator('[data-action="begin-race"]').click()
        page.locator('#finish-preview').click()
        expect(page.locator('.result-time')).to_be_visible()
        page.locator('[data-action="results-next"]').click()
        expect(page.get_by_role('dialog')).to_contain_text('ONE PLACE CLOSER')
        page.locator('[data-action="weekly-back"]').click()
        expect(page.locator('.week-track')).to_have_count(5)
        CHECKS.append('Rivalry detail starts racing and preserves normal results before weekly feedback')

        page.locator('#jump').select_option('challenges')
        page.locator('[data-action="challenge-create"]').click()
        page.locator('#challenge-name').fill('Evening sprint')
        page.locator('#challenge-duration').select_option('3 days')
        page.locator('#challenge-tries').select_option('3')
        page.locator('[data-action="challenge-submit"]').click()
        expect(page.get_by_role('dialog')).to_contain_text('Evening sprint')
        page.locator('[data-action="created-challenges"]').click()
        expect(page.locator('.challenge-detail')).to_contain_text('Evening sprint')
        CHECKS.append('Challenge form retains chosen name, duration and tries in the created folder')

        page.locator('#jump').select_option('create')
        page.locator('[data-action="biome"][data-value="winter"]').click()
        expect(page.locator('.create-foot')).to_contain_text('Packed snow')
        page.locator('.create-foot [data-value="editor"]').click()
        for _ in range(2): page.locator('[data-action="editor-next"]').click()
        page.locator('[data-action="editor-next"]').click()
        page.locator('#finish-preview').click()
        page.locator('.results-bottom [data-value="editor"]').click()
        page.locator('[data-action="editor-next"]').click()
        expect(page.get_by_role('dialog')).to_contain_text('Publish track?')
        page.locator('[data-action="publish-confirm"]').click()
        expect(page.get_by_role('dialog')).to_contain_text('No track was uploaded')
        page.locator('[data-action="my-tracks"]').click()
        expect(page.get_by_role('dialog')).to_contain_text('Published')
        page.keyboard.press('Escape')
        CHECKS.append('Biome selection and guided road/start/test/publish flow complete without external operations')

        page.locator('#jump').select_option('settings')
        page.locator('[data-action="before"]').click()
        expect(page.locator('.compare-dialog img')).to_be_visible()
        assert page.locator('.compare-dialog img').evaluate('(img)=>img.complete && img.naturalWidth>0')
        page.keyboard.press('Escape')
        page.locator('[data-action="notes"]').click()
        expect(page.locator('#design-notes')).to_be_visible()
        page.locator('[data-action="notes"]').click()
        CHECKS.append('Original screenshot comparison, modal Escape and design-note drawer work')

        geometry=[]
        for width,height in [(1440,1000),(960,720),(390,844),(844,390)]:
            page.set_viewport_size({'width':width,'height':height})
            for screen in ['welcome','race','garage','rivalry','challenges','trophies','settings','results','create','store','profile']:
                page.locator('#jump').select_option(screen)
                page.wait_for_timeout(30)
                bounds=page.evaluate('''()=>({viewport:innerWidth,doc:document.documentElement.scrollWidth,game:document.querySelector('#game').getBoundingClientRect().width})''')
                if bounds['doc']>width+1: geometry.append({'width':width,'height':height,'screen':screen,**bounds})
            page.locator('#jump').select_option('race')
            page.screenshot(path=str(OUT / f'07-free-race-{width}x{height}.png'),full_page=True)
        assert not geometry, json.dumps(geometry)
        CHECKS.append('Eleven screens have no document-width overflow at desktop, compact, portrait and landscape viewports')
        assert not ERRORS, ERRORS
        assert not EXTERNAL, EXTERNAL
        CHECKS.append('No browser JavaScript errors and no HTTP(S) requests')
        browser.close()
    report={'status':'passed','checks':CHECKS,'check_count':len(CHECKS),'errors':ERRORS,'external_requests':EXTERNAL,'physical_device_test':False,'game_modified':False}
    (OUT / 'browser-checks.json').write_text(json.dumps(report,indent=2)+'\n',encoding='utf-8')
    print(json.dumps(report,indent=2))


if __name__=='__main__':
    main()
