"""Small, circular wind-loudness guides from the unchanged mastered PCM assets."""
from pathlib import Path
import argparse
import array
import hashlib
import math
import sys
import wave

ROOT = Path(__file__).resolve().parents[1]
BANK = ROOT / "game/assets/audio/ambience"
TARGET = ROOT / "game/track/desert_wind_envelope.gd"
RATE = 20


def build():
    rows = []
    hashes = []
    for name in ["desert_wind", "desert_wind_b", "desert_wind_c"]:
        path = BANK / (name + ".wav")
        with wave.open(str(path), "rb") as source:
            assert source.getsampwidth() == 2 and source.getnchannels() == 1
            rate = source.getframerate()
            values = array.array("h", source.readframes(source.getnframes()))
        if sys.byteorder != "little":
            values.byteswap()
        hop = rate // RATE
        powers = [sum(float(x) ** 2 for x in values[i:i+hop]) / hop
                  for i in range(0, len(values), hop)]
        # A centred 350 ms window follows audible swells without grain flicker.
        rms = [math.sqrt(sum(powers[(i+j) % len(powers)] for j in range(-3, 4)) / 7)
               for i in range(len(powers))]
        ordered = sorted(rms)
        low, high = ordered[len(ordered)//10], ordered[len(ordered)*9//10]
        rows.append([round(max(0, min(1, (x-low)/(high-low))), 5) for x in rms])
        hashes.append([hashlib.sha256(path.read_bytes()).hexdigest(),
                       hashlib.sha256((BANK / (name + ".ogg")).read_bytes()).hexdigest()])
    lines = ["extends RefCounted", "## Generated by scripts/bake_desert_wind_envelope.py; no runtime decoding.",
             "const RATE: float = 20.0", "const HASHES: Array = " + repr(hashes).replace("'", '"'),
             "const LEVELS: Array = ["]
    for row in rows:
        lines.append("\t" + repr(row) + ",")
    lines += ["]", "", "static func sample(variant: int, seconds: float) -> float:",
              "\tvar levels: Array = LEVELS[variant]",
              "\tvar at: float = fposmod(seconds * RATE, float(levels.size()))",
              "\tvar index: int = floori(at)",
              "\treturn lerpf(levels[index], levels[(index + 1) % levels.size()], at - index)", ""]
    return "\n".join(lines).encode()


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    result = build()
    if args.check:
        assert TARGET.read_bytes() == result, "Rebake the changed wind assets"
    else:
        TARGET.write_bytes(result)
    print("DESERT_WIND_ENVELOPE: exact" if args.check else "DESERT_WIND_ENVELOPE: baked")
