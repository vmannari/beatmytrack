def ink(d, colour, width=4):
    return (f'<path d="{d}" fill="{colour}" stroke="{INK}" '
            f'stroke-width="{width}" stroke-linecap="round" stroke-linejoin="round"/>')


def cut(d, colour):
    return (f'<path d="{d}" fill="{PAPER}" stroke="{PAPER}" '
            'stroke-width="14" stroke-linejoin="round"/>' + ink(d, colour))


def line(d, colour=INK, width=4):
    return (f'<path d="{d}" fill="none" stroke="{colour}" '
            f'stroke-width="{width}" stroke-linecap="round" stroke-linejoin="round"/>')


def dot(x, y, r, colour=INK):
    return f'<circle cx="{x}" cy="{y}" r="{r}" fill="{colour}"/>'


